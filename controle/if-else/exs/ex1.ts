/**
 * Estruturas de Controle - if / else
 *
 * Desafio 1 - Verificador de idade
 *
 * - Crie uma variável chamada age do tipo number.
 * - Verifique se a idade é maior ou igual a 18.
 * - Se for, exiba "Maior de idade".
 * - Caso contrário, exiba "Menor de idade".
 */

var age: number = 22;

if (age >= 18) {
  console.log("Maior de idade");
} else {
  console.log("Menor de idade");
}
